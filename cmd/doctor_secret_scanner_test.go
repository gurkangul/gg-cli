// TestChecksumMismatch verifies that when the archive SHA does not match the
// expected SHA, the mismatch is detectable. Uses httptest servers to avoid
// real network calls.
func TestChecksumMismatch(t *testing.T) {
	const archiveName = "gitleaks_8.21.2_linux_x64.tar.gz"
	fakeExpectedSHA := strings.Repeat("0", 64)

	srvChecksums := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		fmt.Fprintf(w, "%s  %s\n", fakeExpectedSHA, archiveName)
	}))
	defer srvChecksums.Close()

	srvArchive := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		fmt.Fprint(w, "this is not a real archive — its SHA will differ from fakeExpectedSHA")
	}))
	defer srvArchive.Close()

	client := srvChecksums.Client()

	gotExpected, err := fetchExpectedSHA(client, srvChecksums.URL, archiveName)
	if err != nil {
		t.Fatalf("fetchExpectedSHA: %v", err)
	}

	resp, err := client.Get(srvArchive.URL) //nolint:noctx
	if err != nil {
		t.Fatalf("get archive: %v", err)
	}
	defer resp.Body.Close()
	data, _ := io.ReadAll(resp.Body)
	sum := sha256.Sum256(data)
	gotSHA := hex.EncodeToString(sum[:])

	// The real installer compares gotSHA != expectedSHA to detect mismatch.
	if gotSHA == gotExpected {
		t.Fatal("test setup error: archive SHA unexpectedly matches fake expected SHA")
	}
}

// TestInstallGitPreCommitDispatcher_Fresh verifies the dispatcher is written
// when no .git/hooks/pre-commit exists.
func TestInstallGitPreCommitDispatcher_Fresh(t *testing.T) {
	root := t.TempDir()
	gitHooksDir := filepath.Join(root, ".git", "hooks")
	if err := os.MkdirAll(gitHooksDir, 0o755); err != nil {
		t.Fatal(err)
	}

	preCommitDir := filepath.Join(root, ".gg", "hooks", "pre-commit.d")
	if err := installGitPreCommitDispatcher(root, preCommitDir); err != nil {
		t.Fatalf("installGitPreCommitDispatcher: %v", err)
	}

	data, err := os.ReadFile(filepath.Join(gitHooksDir, "pre-commit")) //nolint:gosec
	if err != nil {
		t.Fatalf("pre-commit hook not written: %v", err)
	}
	body := string(data)
	if !strings.Contains(body, "pre-commit.d") {
		t.Error("dispatcher script should reference pre-commit.d")
	}
	if !strings.HasPrefix(body, "#!/bin/sh") {
		t.Error("dispatcher script should start with #!/bin/sh")
	}
}

// TestInstallGitPreCommitDispatcher_ExistingForeignHook verifies that a
// foreign .git/hooks/pre-commit is not overwritten — only the fan-out
// stanza is appended.
func TestInstallGitPreCommitDispatcher_ExistingForeignHook(t *testing.T) {
	root := t.TempDir()
	gitHooksDir := filepath.Join(root, ".git", "hooks")
	if err := os.MkdirAll(gitHooksDir, 0o755); err != nil {
		t.Fatal(err)
	}
	existingBody := "#!/bin/sh\n# existing hook\necho hello\n"
	dispatcherPath := filepath.Join(gitHooksDir, "pre-commit")
	if err := os.WriteFile(dispatcherPath, []byte(existingBody), 0o755); err != nil {
		t.Fatal(err)
	}

	preCommitDir := filepath.Join(root, ".gg", "hooks", "pre-commit.d")
	if err := installGitPreCommitDispatcher(root, preCommitDir); err != nil {
		t.Fatalf("installGitPreCommitDispatcher: %v", err)
	}

	data, err := os.ReadFile(dispatcherPath) //nolint:gosec
	if err != nil {
		t.Fatalf("read dispatcher: %v", err)
	}
	body := string(data)
	if !strings.Contains(body, "existing hook") {
		t.Error("original hook content should be preserved")
	}
	if !strings.Contains(body, "pre-commit.d") {
		t.Error("fan-out stanza should be appended")
	}
}

// TestInstallGitPreCommitDispatcher_Idempotent verifies that running the
// installer twice when the dispatcher already contains pre-commit.d is a no-op.
func TestInstallGitPreCommitDispatcher_Idempotent(t *testing.T) {
	root := t.TempDir()
	if err := os.MkdirAll(filepath.Join(root, ".git", "hooks"), 0o755); err != nil {
		t.Fatal(err)
	}

	preCommitDir := filepath.Join(root, ".gg", "hooks", "pre-commit.d")
	if err := installGitPreCommitDispatcher(root, preCommitDir); err != nil {
		t.Fatalf("first install: %v", err)
	}
	firstContent, _ := os.ReadFile(filepath.Join(root, ".git", "hooks", "pre-commit")) //nolint:gosec

	if err := installGitPreCommitDispatcher(root, preCommitDir); err != nil {
		t.Fatalf("second install: %v", err)
	}
	secondContent, _ := os.ReadFile(filepath.Join(root, ".git", "hooks", "pre-commit")) //nolint:gosec

	if string(firstContent) != string(secondContent) {
		t.Error("second install should not modify the dispatcher")
	}
}

