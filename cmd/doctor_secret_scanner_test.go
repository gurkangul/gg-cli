// TestGitleaksPlatformKey verifies the platform→slug mapping for the current
// running platform and that an unsupported platform returns an error.
func TestGitleaksPlatformKey(t *testing.T) {
	got, err := gitleaksPlatformKey()
	switch {
	case runtime.GOOS == "darwin" && runtime.GOARCH == "arm64":
		if err != nil || got != "darwin_arm64" {
			t.Errorf("darwin/arm64: got (%q, %v)", got, err)
		}
	case runtime.GOOS == "darwin" && runtime.GOARCH == "amd64":
		if err != nil || got != "darwin_x64" {
			t.Errorf("darwin/amd64: got (%q, %v)", got, err)
		}
	case runtime.GOOS == "linux" && runtime.GOARCH == "arm64":
		if err != nil || got != "linux_arm64" {
			t.Errorf("linux/arm64: got (%q, %v)", got, err)
		}
	case runtime.GOOS == "linux" && runtime.GOARCH == "amd64":
		if err != nil || got != "linux_x64" {
			t.Errorf("linux/amd64: got (%q, %v)", got, err)
		}
	case runtime.GOOS == "windows" && runtime.GOARCH == "amd64":
		if err != nil || got != "windows_x64" {
			t.Errorf("windows/amd64: got (%q, %v)", got, err)
		}
	default:
		// Unsupported platform should return error.
		if err == nil {
			t.Errorf("unexpected platform %s/%s: expected error, got key %q", runtime.GOOS, runtime.GOARCH, got)
		}
	}
}

// TestFetchExpectedSHA_Found verifies the happy path: the SHA is returned
// when the archive name appears in a well-formed checksums.txt response.
func TestFetchExpectedSHA_Found(t *testing.T) {
	const archiveName = "gitleaks_8.21.2_darwin_arm64.tar.gz"
	const expectedSHA = "aabbccddeeff00112233445566778899aabbccddeeff00112233445566778899"

	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		fmt.Fprintf(w, "# comment line\n\n")
		fmt.Fprintf(w, "%s  gitleaks_8.21.2_linux_x64.tar.gz\n", strings.Repeat("0", 64))
		fmt.Fprintf(w, "%s  %s\n", expectedSHA, archiveName)
	}))
	defer srv.Close()

	got, err := fetchExpectedSHA(srv.Client(), srv.URL, archiveName)
	if err != nil {
		t.Fatalf("fetchExpectedSHA: unexpected error: %v", err)
	}
	if got != expectedSHA {
		t.Errorf("fetchExpectedSHA = %q, want %q", got, expectedSHA)
	}
}

